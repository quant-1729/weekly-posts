#!/usr/bin/env node
// Creates .env.local for a NEW machine, so the app runs locally without copying any secret around.
//
//   node scripts/setup/make-env-local.mjs                 # offline: mock database, mock email, AI fixtures (no Google needed)
//   node scripts/setup/make-env-local.mjs --live-ai \
//        --project=<gcp-project-id> [--location=global] [--credentials=<path to Google credential JSON>]
//                                                          # same, but real Gemini/Imagen on Vertex AI
//   add --force to overwrite an existing .env.local (a backup .env.local.bak is written first)
//
// It generates fresh random values for the local-only secrets (AUTH_SECRET, EMAIL_LINK_SECRET, CRON_SECRET,
// TOKEN_ENCRYPTION_KEY). Nothing is read from or sent to the cloud. Never commit .env.local (.gitignore covers it).

import { randomBytes } from 'node:crypto';
import { copyFileSync, existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, ...v] = a.replace(/^--/, '').split('=');
    return [k, v.length ? v.join('=') : true];
  }),
);

const file = path.join(process.cwd(), '.env.local');
if (existsSync(file) && !args.force) {
  console.error('.env.local already exists. Re-run with --force to replace it (a .env.local.bak backup is kept).');
  process.exit(1);
}
if (existsSync(file)) copyFileSync(file, `${file}.bak`);

const rand = (n) => randomBytes(n).toString('base64url');
const live = Boolean(args['live-ai']);
if (live && !args.project) {
  console.error('--live-ai needs --project=<Google Cloud project id that has Vertex AI enabled>.');
  process.exit(1);
}

const lines = [
  '# Local development settings, generated by scripts/setup/make-env-local.mjs. Never commit this file.',
  '# Full list of settings with explanations: .env.example. Setup guide: docs/SETUP.md.',
  '',
  'NEXT_PUBLIC_APP_URL=http://localhost:3000',
  '',
  '# Data: a local PGlite database in .data/ (created on first start, migrations applied automatically).',
  'DATA_BACKEND=mock',
  'STORAGE_BACKEND=mock',
  '',
  '# Local-only secrets (fresh random values; not the production ones).',
  `AUTH_SECRET=${rand(48)}`,
  `EMAIL_LINK_SECRET=${rand(48)}`,
  `CRON_SECRET=${rand(32)}`,
  `TOKEN_ENCRYPTION_KEY=${randomBytes(32).toString('base64')}`,
  '',
  '# Email: left blank = mock outbox. Sign-in links appear at http://localhost:3000/dev/outbox (no real email is sent).',
  'RESEND_API_KEY=',
  'EMAIL_FROM=',
  '',
  '# Who may open /admin in the main app (comma-separated).',
  'ADMIN_EMAILS=priyanshuagrawal1729@gmail.com,shuklabhavan28@gmail.com',
  '',
  '# AI: "fixture" = canned answers, no Google account needed, no cost. "live" = real Vertex AI calls (cost money).',
  `AI_MODE=${live ? 'live' : 'fixture'}`,
  `GOOGLE_GENAI_USE_VERTEXAI=${live ? 'true' : ''}`,
  `GOOGLE_CLOUD_PROJECT=${live ? args.project : ''}`,
  `GOOGLE_CLOUD_LOCATION=${live ? (args.location || 'global') : ''}`,
  '# Blank = use Application Default Credentials from `gcloud auth application-default login` (recommended).',
  `GOOGLE_APPLICATION_CREDENTIALS=${typeof args.credentials === 'string' ? args.credentials.replace(/\\/g, '/') : ''}`,
  'IMAGEN_MODEL=',
  'GEMINI_MODEL=',
  '',
  '# Optional integrations (leave blank locally unless you are testing them): see .env.example for each.',
  'YOUTUBE_API_KEY=',
  'IDEAS_BUSINESS_DISCOVERY=',
  'META_APP_ID=',
  'META_APP_SECRET=',
  'INSTAGRAM_APP_ID=',
  'INSTAGRAM_APP_SECRET=',
  'CUTOUT_URL=',
  'CUTOUT_TOKEN=',
  'GEOIP_DB_PATH=',
  '',
];

writeFileSync(file, lines.join('\n'), { encoding: 'utf8', mode: 0o600 });
console.log(`Wrote ${file} (${live ? 'live AI on ' + args.project : 'offline: AI fixtures'}, mock database and email).`);
console.log('Next: npm ci && npm run dev, then open http://localhost:3000 (sign-in links: http://localhost:3000/dev/outbox).');
